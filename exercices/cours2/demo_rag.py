import json
import sqlite3

from ollama import Message, chat

MODEL = "ministral-3:3b"  # qwen2.5:1.5b misreads "mid-May" and makes up the return flight
MAX_STEPS = 5  # cap on model calls, so a confused model cannot loop forever


# The data source: an embedded SQLite database, held in memory.
# The model never sees this table; it only sees what search_flights returns.
db = sqlite3.connect(":memory:")
db.execute("""
    CREATE TABLE flights (
        airline   TEXT,
        from_city TEXT,
        to_city   TEXT,
        date      TEXT,  -- YYYY-MM-DD
        departure TEXT,  -- HH:MM
        price_eur INTEGER
    )
""")
# Every day of May 2026, the same flights; the further from mid-May, the higher the price.
schedule = [
    # airline,    from_city, to_city,  departure, price_eur on the cheapest day
    ("TAP",       "Paris",  "Lisbon", "06:10", 45),
    ("Iberia",    "Paris",  "Lisbon", "09:00", 90),
    ("Transavia", "Paris",  "Lisbon", "14:25", 110),
    ("Iberia",    "Lisbon", "Paris",  "07:05", 40),
    ("TAP",       "Lisbon", "Paris",  "18:30", 60),
]
for day in range(1, 32):
    for airline, from_city, to_city, departure, price in schedule:
        cheapest_day = 15 if from_city == "Paris" else 18
        db.execute("INSERT INTO flights VALUES (?, ?, ?, ?, ?, ?)",
                   (airline, from_city, to_city, f"2026-05-{day:02d}", departure,
                    price + 5 * abs(day - cheapest_day)))


def search_flights(from_city: str, to_city: str, from_date: str, to_date: str) -> str:
    """Return available flights for a route, between two dates.

    Args:
        from_city: City of departure, in English (e.g. Paris).
        to_city: City of arrival, in English (e.g. Lisbon).
        from_date: First date of the search, as YYYY-MM-DD.
        to_date: Last date of the search, as YYYY-MM-DD.
    """
    # The model chose the arguments; the harness turns them into a query on the database
    sql = ("SELECT date, airline, departure, price_eur FROM flights "
           "WHERE from_city = ? AND to_city = ? AND date BETWEEN ? AND ? ORDER BY date, departure")
    params = (from_city, to_city, from_date, to_date)
    rows = db.execute(sql, params).fetchall()
    print(f"\n=== Query run by the harness ===\n{sql}\n  with {params}")
    if not rows:
        return f"No flight from {from_city} to {to_city} between {from_date} and {to_date}."
    return "\n".join(f"{date} {airline} {departure} {price} €" for date, airline, departure, price in rows)


def stream_chat(title: str, **kwargs) -> Message:
    """Call the model, printing its text under title as it is generated; return the whole message."""
    content, tool_calls = "", []
    for chunk in chat(**kwargs, stream=True):
        if chunk.message.content and not content:
            print(f"\n=== {title} ===")
        print(chunk.message.content, end="", flush=True)
        content += chunk.message.content
        # a tool call is not streamed: it comes whole, in one chunk
        tool_calls += chunk.message.tool_calls or []
    if content:
        print()
    return Message(role="assistant", content=content, tool_calls=tool_calls or None)


def show(title: str, data) -> None:
    print(f"\n=== {title} ===")
    print(json.dumps(data, indent=2, ensure_ascii=False))


messages = [
    # what the model cannot guess: today's date, and where the user lives
    {"role": "system", "content": "Today is 2026-04-20: all dates are in 2026. The user lives in Paris. "
                                  "Use search_flights to find flights; never invent one. Just respond to the question and be very concise."},
    # the running example of the lecture
    {"role": "user", "content": "Plan a 3-day trip to Lisbon, with a budget of 500 €, in mid-May. "
                                "I want something cheap, with convenient outbound and return times."},
]
tools = [search_flights]

for _ in range(MAX_STEPS):
    # temperature 0: the same output at every run of the demo
    message = stream_chat("Answer of the model", model=MODEL, messages=messages, tools=tools,
                          options={"temperature": 0})
    messages.append(message)
    if not message.tool_calls:
        break

    # 1. Retrieve: the model generates the query, as a tool call; the harness runs it
    for tool_call in message.tool_calls:
        call = tool_call.function
        show("Query generated by the model", {"name": call.name, "arguments": call.arguments})
        result = search_flights(**call.arguments)
        print(f"\n=== Result ===\n{result}")
        # 2. Augment: the result enters the context, as a "tool" message
        messages.append({"role": "tool", "content": result, "tool_name": call.name})

